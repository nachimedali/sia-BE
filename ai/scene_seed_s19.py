def _scene(
    key: str,
    label: str,
    category: str,
    fits: tuple[str, ...],
    person: str,
    *,
    lengths: tuple[str, ...],
    beats: tuple[str, ...],
    frame: str,
    motion: str,
    script: tuple[str, str, str],
    hooks: tuple[str, ...],
    locations: tuple[str, ...],
    protect: str,
    needs: str = "",
    available: bool = True,
    sort: int = 0,
) -> dict[str, Any]:
    direction = DIRECTIONS[key]
    row = _template(
        key,
        label,
        category,
        fits,
        person,
        "people" if person == "required" else "product",
        lengths=lengths,
        beats=beats,
        frame=frame,
        motion=motion,
        script=script,
        hooks=hooks,
        locations=locations,
        needs=needs,
        premium=True,
        capture=str(direction.get("capture") or ""),
        land=direction.get("route") == "L",
        available=available,
        description="" if available else _SOON,
        sort=sort,
        protect=protect,
    )
    row["metadata"]["direction"] = direction
    row["metadata"]["pro"] = True
    return row


