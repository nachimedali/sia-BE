def translations_for(kind: str, key: str) -> dict[str, Any]:
    """The `translations` value for one seeded row, `{}` when it has none."""
    row = TRANSLATIONS.get(f"{kind}|{key}")
    if row is None:
        return {}
    out: dict[str, Any] = {}
    for lang, (label, description) in (("fr", row[:2]), ("it", row[2:])):
        out[lang] = {"label": label, **({"description": description} if description else {})}
    return out
